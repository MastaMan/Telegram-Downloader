"""Durable, account-scoped queue; no Telegram credentials in this database."""
import json
import os
import re
import sqlite3
from collections import Counter
from pathlib import Path

CHUNK = 512 * 1024
SPEED_LIMITS = (0, 10, 5, 2, 1, 0.5, 0.25)
QUEUE_PAGE_SIZE = 200
QUEUE_ORDER = "CASE WHEN state='downloading' THEN 0 WHEN state='done' AND verification='checking' THEN 1 WHEN state!='done' THEN 2 ELSE 3 END"
# Skipped jobs stay in the queue history but are not downloaded until the
# global rules that skipped them change.
UNFINISHED = "state NOT IN ('done','skipped')"
# Archive names generated by the site's PHP uploader, e.g. 7407604.67a7dac35b142.rar.
DEFAULT_NAME_FILTER = r'^[0-9a-z]+\.[0-9a-z]+\.(zip|rar)$'
FILTER_MODES = ('regex', 'text')
SKIP_KNOWN = 'Skipped: a file with this name or Telegram document was already downloaded.'
SKIP_FILTER = 'Skipped: the filename does not match the name filter.'


def name_matcher(settings):
    """Return the global filename predicate, or None when the filter is off."""
    if not settings.get('name_filter_enabled', True):
        return None
    pattern = settings.get('name_filter', DEFAULT_NAME_FILTER)
    if settings.get('name_filter_mode', 'regex') == 'text':
        needle = pattern.casefold()
        return lambda name: needle in name.casefold()
    try:
        regex = re.compile(pattern)
    except re.error as exc:
        raise ValueError(f'Invalid regular expression: {exc}') from None
    return lambda name: regex.search(name) is not None


class SkipRules:
    """Global download rules shared by all chats: name filter and known files."""
    def __init__(self, matcher, known):
        self.matcher = matcher
        # (case-folded names, document IDs) completed in any chat, or None when off.
        self.known = known

    def reason(self, job):
        if self.known is not None and (job['name'].casefold() in self.known[0]
                                       or str(job['document']) in self.known[1]):
            return SKIP_KNOWN
        if self.matcher is not None and not self.matcher(job['name']):
            return SKIP_FILTER
        return None

    def claim(self, job):
        # Concurrent duplicates in the same pass are skipped as soon as one is claimed.
        if self.known is not None:
            self.known[0].add(job['name'].casefold())
            self.known[1].add(str(job['document']))


def speed_limit(value=None):
    """Saved limits are MB/s (binary megabytes); zero means unlimited."""
    try:
        limit = float(value)
        return limit if limit in SPEED_LIMITS else 0
    except (TypeError, ValueError, OverflowError):
        return 0


def parallel_downloads(value=None):
    """Use a bounded pool even if settings were edited outside the app."""
    try:
        return max(1, min(20, int(value)))
    except (TypeError, ValueError, OverflowError):
        return 20


def is_network_path(path):
    """SQLite locking and WAL are unreliable on network filesystems; synced local folders are fine."""
    text = str(path)
    if text.startswith(('\\\\', '//')):
        return True
    if os.name == 'nt':
        import ctypes
        drive = os.path.splitdrive(os.path.abspath(text))[0]
        if drive:
            return ctypes.windll.kernel32.GetDriveTypeW(drive + '\\') == 4  # DRIVE_REMOTE
    return False


def atomic_write(path: Path, data: bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    with open(temp, "wb") as f:
        f.write(data)
        f.flush()
        os.fsync(f.fileno())
    os.replace(temp, path)


def load_settings(path):
    if not path.exists():
        return {}
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(value, dict):
            raise ValueError("Invalid settings")
        return value
    except (ValueError, UnicodeError):
        # Preserve the broken file for inspection; defaults remain usable.
        backup = path.with_suffix(".broken.json")
        os.replace(path, backup)
        return {}


def safe_name(name):
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f\x7f]', "_", name)
    name = name.rstrip(" .")
    extension = name[-4:] if archive_extension(name, None) else '.zip'
    stem = name[:-4] if archive_extension(name, None) else name
    if not name:
        stem = "archive"
    if stem.split(".")[0].upper() in {"CON", "PRN", "AUX", "NUL", *[f"COM{i}" for i in range(1, 10)], *[f"LPT{i}" for i in range(1, 10)]}:
        stem = "_" + stem
    return stem + extension


class FilenameAllocator:
    """Reserve names before workers yield, including queued files and disk entries."""
    def __init__(self, paths):
        self.reserved = Counter(self.key(path) for path in paths if path)
        self.directories = {}

    @staticmethod
    def key(path):
        return str(Path(path).absolute()).casefold()

    def allocate(self, parent, name, previous=None):
        parent = Path(parent)
        directory = self.key(parent)
        if directory not in self.directories:
            self.directories[directory] = {
                entry.name.casefold() for entry in parent.iterdir()
            } if parent.exists() else set()
        entries = self.directories[directory]
        previous_key = self.key(previous) if previous else None
        number = 1
        while True:
            filename = name if number == 1 else f'__dup_{number}__{name}'
            target = parent / filename
            part = target.with_name(filename + '.part')
            reserved = any(self.reserved[self.key(path)] >
                           (1 if self.key(path) == previous_key else 0)
                           for path in (target, part))
            # Windows checks are case insensitive. The snapshot also gives
            # Windows semantics to tests on case-sensitive filesystems.
            occupied = any(path.name.casefold() in entries for path in (target, part))
            # Avoid probing names the filesystem cannot represent. Transfer
            # reports these as errors rather than silently shortening them.
            if len((filename + '.part').encode('utf-16-le')) // 2 <= 255:
                occupied |= any(os.path.lexists(path) for path in (target, part))
            if not reserved and not occupied:
                if previous_key:
                    self.reserved[previous_key] -= 1
                self.reserved[self.key(target)] += 1
                return target
            number += 1


def archive_extension(name, mime):
    """Select ZIP/RAR attachments; an explicit filename wins over MIME metadata."""
    if name:
        return next((extension for extension in ('.zip', '.rar')
                     if name.lower().endswith(extension)), None)
    mime = (mime or '').split(';', 1)[0].strip().lower()
    if mime in {'application/zip', 'application/x-zip-compressed'}:
        return '.zip'
    if mime in {'application/vnd.rar', 'application/x-rar-compressed', 'application/x-rar', 'application/rar'}:
        return '.rar'
    return None


def resume_offset(path, expected):
    size = path.stat().st_size if path.exists() else 0
    if size > expected:
        raise ValueError("Partial file exceeds expected size")
    return size if size == expected else size // CHUNK * CHUNK


class Store:
    def __init__(self, path):
        self.progress_pending = {}
        self.db = sqlite3.connect(path)
        self.db.row_factory = sqlite3.Row
        self.db.execute("PRAGMA journal_mode=WAL")
        self.db.execute("PRAGMA synchronous=FULL")
        self.db.executescript('''
        CREATE TABLE IF NOT EXISTS jobs (
          account INTEGER, chat INTEGER, message INTEGER, document TEXT,
          name TEXT, size INTEGER, path TEXT, done INTEGER DEFAULT 0,
          state TEXT DEFAULT 'queued', error TEXT DEFAULT '',
          PRIMARY KEY(account, chat, message));
        CREATE TABLE IF NOT EXISTS scans (
          account INTEGER, chat INTEGER, cursor INTEGER DEFAULT 0,
          PRIMARY KEY(account, chat));
        CREATE TABLE IF NOT EXISTS filename_moves (
          account INTEGER, chat INTEGER, message INTEGER, plan TEXT NOT NULL,
          PRIMARY KEY(account, chat, message));
        CREATE TABLE IF NOT EXISTS local_files (
          path TEXT PRIMARY KEY, name TEXT NOT NULL, size INTEGER NOT NULL, status TEXT NOT NULL);
        ''')
        with self.db:
            columns = {row[1] for row in self.db.execute('PRAGMA table_info(jobs)')}
            for column, default in [('verification', 'pending'), ('verification_error', ''), ('quarantine_path', '')]:
                if column not in columns:
                    self.db.execute(f"ALTER TABLE jobs ADD COLUMN {column} TEXT NOT NULL DEFAULT '{default}'")
            if 'naming_version' not in columns:
                self.db.execute("ALTER TABLE jobs ADD COLUMN naming_version INTEGER NOT NULL DEFAULT 0")
            if 'partial_path' not in columns:
                self.db.execute("ALTER TABLE jobs ADD COLUMN partial_path TEXT NOT NULL DEFAULT ''")
            if self.db.execute('PRAGMA user_version').fetchone()[0] < 1:
                # Earlier versions skipped RAR attachments. Revisit history once,
                # without discarding completed ZIPs, partial files or queued jobs.
                self.db.execute('UPDATE scans SET cursor=0')
                self.db.execute('PRAGMA user_version=1')
            self.db.execute("UPDATE jobs SET state='queued' WHERE state='downloading'")
            self.db.execute("UPDATE jobs SET verification='pending' WHERE verification='checking'")
            self.db.execute("CREATE INDEX IF NOT EXISTS pending_archive_checks ON jobs(account,chat,message) WHERE state='done' AND verification='pending'")
            self.db.execute(f"CREATE INDEX IF NOT EXISTS queue_display_order ON jobs(account,chat,({QUEUE_ORDER}),message)")

    def cursor(self, account, chat):
        row = self.db.execute("SELECT cursor FROM scans WHERE account=? AND chat=?", (account, chat)).fetchone()
        return row[0] if row else 0

    def contains(self, account, chat, message):
        return self.db.execute('SELECT 1 FROM jobs WHERE account=? AND chat=? AND message=?',
                               (account, chat, message)).fetchone() is not None

    def scanned(self, account, chat, message, item=None):
        with self.db:
            if item:
                self.db.execute('''INSERT OR IGNORE INTO jobs
                    (account,chat,message,document,name,size,path,naming_version) VALUES (?,?,?,?,?,?,?,?)''',
                    (account, chat, message, str(item['document']), item['name'], item['size'], str(item['path']),
                     item.get('naming_version', 0)))
            self.db.execute('''INSERT INTO scans VALUES (?,?,?) ON CONFLICT(account,chat)
                DO UPDATE SET cursor=MAX(cursor,excluded.cursor)''', (account, chat, message))

    def stage_progress(self, account, chat, message, done):
        key = (account, chat, message)
        if key not in self.progress_pending:
            row = self.db.execute('SELECT done,size FROM jobs WHERE account=? AND chat=? AND message=?', key).fetchone()
            if row is None:
                raise ValueError('Unknown download')
            self.progress_pending[key] = [row['done'], row['size'], done]
        else:
            self.progress_pending[key][2] = done

    def flush_progress(self):
        if not self.progress_pending:
            return
        # One durable transaction for all active transfers, not one per callback.
        with self.db:
            self.db.executemany('UPDATE jobs SET done=? WHERE account=? AND chat=? AND message=?',
                                [(value[2], *key) for key, value in self.progress_pending.items()])
        self.progress_pending.clear()

    def update(self, account, chat, message, **values):
        if not values.keys() <= {"done", "state", "error", "verification", "verification_error", "quarantine_path",
                                "path", "name", "naming_version", "partial_path"}:
            raise ValueError("Invalid update")
        key = (account, chat, message)
        if key in self.progress_pending:
            values.setdefault('done', self.progress_pending[key][2])
        with self.db:
            self.db.execute("UPDATE jobs SET " + ",".join(f"{key}=?" for key in values) +
                            " WHERE account=? AND chat=? AND message=?",
                            (*values.values(), account, chat, message))
        self.progress_pending.pop(key, None)

    def filename_allocator(self):
        paths = [path for row in self.db.execute('SELECT path,partial_path,quarantine_path FROM jobs')
                 for path in row]
        paths.extend(json.loads(row[0])['destination'] for row in self.db.execute('SELECT plan FROM filename_moves'))
        return FilenameAllocator(paths)

    def legacy_name_jobs(self, account, chat):
        return [dict(row) for row in self.db.execute(
            "SELECT * FROM jobs WHERE account=? AND chat=? AND state='done' AND naming_version=0 ORDER BY message",
            (account, chat))]

    def filename_moves(self, account, chat):
        return [(row['message'], json.loads(row['plan'])) for row in self.db.execute(
            'SELECT message,plan FROM filename_moves WHERE account=? AND chat=? ORDER BY message', (account, chat))]

    def plan_filename_move(self, account, chat, message, plan):
        with self.db:
            self.db.execute('INSERT INTO filename_moves VALUES (?,?,?,?)',
                            (account, chat, message, json.dumps(plan)))

    def finish_filename_move(self, account, chat, message, plan):
        column = 'quarantine_path' if plan['quarantined'] else 'path'
        with self.db:
            self.db.execute(f'UPDATE jobs SET {column}=?,name=?,naming_version=2 WHERE account=? AND chat=? AND message=?',
                            (plan['destination'], plan['name'], account, chat, message))
            self.db.execute('DELETE FROM filename_moves WHERE account=? AND chat=? AND message=?',
                            (account, chat, message))

    def cancel_filename_move(self, account, chat, message):
        with self.db:
            self.db.execute('DELETE FROM filename_moves WHERE account=? AND chat=? AND message=?',
                            (account, chat, message))

    def jobs(self, account, chat, pending=False, limit=None):
        query = "SELECT * FROM jobs WHERE account=? AND chat=?"
        if pending:
            query += " AND state!='done'"
        query += " ORDER BY message"
        if limit is not None:
            query += f" LIMIT {int(limit)}"
        rows = [dict(row) for row in self.db.execute(query, (account, chat))]
        for row in rows:
            pending = self.progress_pending.get((account, chat, row['message']))
            if pending is not None:
                row['done'] = pending[2]
        return rows

    def next_job(self, account, chat, after=0):
        row = self.db.execute(f"SELECT * FROM jobs WHERE account=? AND chat=? AND message>? AND {UNFINISHED} ORDER BY message LIMIT 1",
                              (account, chat, after)).fetchone()
        return dict(row) if row else None

    def known_files(self):
        """Names and Telegram documents completed in any chat; quarantined files do not count."""
        names, documents = set(), set()
        for name, document in self.db.execute(
                "SELECT name, document FROM jobs WHERE state='done' AND verification!='quarantined'"):
            names.add(name.casefold())
            documents.add(document)
        # Archives adopted from the earlier scripts count by their original name.
        names.update(name.casefold() for (name,) in self.db.execute('SELECT name FROM local_files'))
        return names, documents

    def tracked_paths(self):
        return {FilenameAllocator.key(path) for row in self.db.execute('SELECT path,partial_path,quarantine_path FROM jobs')
                for path in row if path}

    def add_local_file(self, path, name, size, status):
        with self.db:
            self.db.execute('INSERT OR REPLACE INTO local_files VALUES (?,?,?,?)', (str(path), name, size, status))

    def apply_skip_rules(self, account, chat, rules):
        """Skip or restore every waiting job in one transaction; return skip counts by reason."""
        counts = Counter()
        changes = []
        for row in self.db.execute("SELECT message,name,document,state,error FROM jobs "
                                   "WHERE account=? AND chat=? AND state NOT IN ('done','downloading')",
                                   (account, chat)):
            reason = rules.reason(row)
            if reason:
                counts[reason] += 1
                if row['state'] != 'skipped' or row['error'] != reason:
                    changes.append(('skipped', reason, account, chat, row['message']))
            elif row['state'] == 'skipped':
                changes.append(('queued', '', account, chat, row['message']))
        if changes:
            with self.db:
                self.db.executemany('UPDATE jobs SET state=?, error=? WHERE account=? AND chat=? AND message=?', changes)
        return counts

    def queue_page(self, account, chat, mode='unfinished', page=0):
        conditions = {'unfinished': f" AND {UNFINISHED}", 'downloaded': " AND state='done'",
                      'skipped': " AND state='skipped'", 'all': ''}
        if mode not in conditions:
            raise ValueError('Unknown queue filter')
        where = 'account=? AND chat=?' + conditions[mode]
        total = self.db.execute(f'SELECT COUNT(*) FROM jobs WHERE {where}', (account, chat)).fetchone()[0]
        pages = max(1, (total + QUEUE_PAGE_SIZE - 1) // QUEUE_PAGE_SIZE)
        page = max(0, min(int(page), pages - 1))
        rows = [dict(row) for row in self.db.execute(
            f'SELECT * FROM jobs WHERE {where} ORDER BY {QUEUE_ORDER},message LIMIT ? OFFSET ?',
            (account, chat, QUEUE_PAGE_SIZE, page * QUEUE_PAGE_SIZE))]
        for row in rows:
            progress = self.progress_pending.get((account, chat, row['message']))
            if progress is not None:
                row['done'] = progress[2]
        return dict(rows=rows, page=page, pages=pages, matching=total, mode=mode, page_size=QUEUE_PAGE_SIZE)

    def next_check_job(self, account, chat, after=0):
        row = self.db.execute("SELECT * FROM jobs WHERE account=? AND chat=? AND message>? AND state='done' AND verification!='quarantined' ORDER BY message LIMIT 1",
                              (account, chat, after)).fetchone()
        return dict(row) if row else None

    def next_pending_check(self, account, chat):
        row = self.db.execute("SELECT * FROM jobs WHERE account=? AND chat=? AND state='done' AND verification='pending' ORDER BY message LIMIT 1",
                              (account, chat)).fetchone()
        return dict(row) if row else None

    def pending_quarantines(self, account, chat):
        return [dict(row) for row in self.db.execute(
            "SELECT * FROM jobs WHERE account=? AND chat=? AND verification='quarantining'", (account, chat))]

    def summary(self, account, chat):
        row = self.db.execute('''SELECT COUNT(*) total, COALESCE(SUM(size),0) bytes,
            COALESCE(SUM(MIN(done,size)),0) received,
            COALESCE(SUM(state='done'),0) complete,
            COALESCE(SUM(state='error'),0) failed,
            COALESCE(SUM(state='skipped'),0) skipped,
            COALESCE(SUM(verification='quarantined'),0) quarantined,
            COALESCE(SUM(verification='ok'),0) verified,
            COALESCE(SUM(state='done' AND verification='pending'),0) unchecked,
            COALESCE(SUM(verification='error'),0) check_failed
            FROM jobs WHERE account=? AND chat=?''', (account, chat)).fetchone()
        result = dict(row)
        result['received'] += sum(min(done, size) - min(saved, size)
                                  for (a, c, _), (saved, size, done) in self.progress_pending.items()
                                  if (a, c) == (account, chat))
        return result

    def close(self):
        try:
            self.flush_progress()
        finally:
            self.db.close()
